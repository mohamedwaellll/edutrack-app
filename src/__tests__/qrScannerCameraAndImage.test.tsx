// @vitest-environment jsdom
import React from 'react';
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { render, screen, fireEvent, act } from '@testing-library/react';
import ReactDOMServer from 'react-dom/server';
import jsQR from 'jsqr';
import { AttendanceQRScanner } from '../components/AttendanceQRScanner';
import StudentIdCard, { StudentCardData } from '../components/StudentIdCard';
import { QRCodeSVG } from 'qrcode.react';

describe('Milestone 3: Camera Stream Cleanup & Real Card QR Decoding', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  describe('1. Late-Arriving Camera Stream Cleanup', () => {
    let mockTrack: { stop: any; readyState: string };
    let mockStream: { getTracks: any };
    let getUserMediaResolve: ((stream: any) => void) | null = null;
    let getUserMediaReject: ((err: any) => void) | null = null;

    beforeEach(() => {
      mockTrack = {
        stop: vi.fn(),
        readyState: 'live',
      };
      mockStream = {
        getTracks: vi.fn(() => [mockTrack]),
      };

      Object.defineProperty(global.navigator, 'mediaDevices', {
        writable: true,
        configurable: true,
        value: {
          getUserMedia: vi.fn().mockImplementation(() => {
            return new Promise((resolve, reject) => {
              getUserMediaResolve = resolve;
              getUserMediaReject = reject;
            });
          }),
        },
      });
    });

    afterEach(() => {
      getUserMediaResolve = null;
      getUserMediaReject = null;
    });

    it('immediately stops any late-arriving media stream if user clicked Stop Camera while permission was pending', async () => {
      const mockClasses = [
        { id: 'group-1', name: 'Physics 101', grade_level: 'Grade 10', subject: 'Physics', room: '101', capacity: 30 }
      ];

      render(
        <AttendanceQRScanner
          classesList={mockClasses}
          selectedGroupId="group-1"
          onSelectGroupId={vi.fn()}
        />
      );

      const startBtn = screen.getByRole('button', { name: /start camera/i });
      fireEvent.click(startBtn);

      // Camera request is pending (permission dialog open). Now user clicks switch to upload or manual stop
      const uploadTabBtn = screen.getByRole('button', { name: /upload image/i });
      fireEvent.click(uploadTabBtn);

      // Now the pending getUserMedia permission resolves after mode was switched
      await act(async () => {
        if (getUserMediaResolve) {
          getUserMediaResolve(mockStream);
        }
      });

      // The late-arriving stream MUST have all its tracks stopped immediately to avoid webcam remaining active!
      expect(mockTrack.stop).toHaveBeenCalled();
    });

    it('immediately stops late-arriving media stream if component unmounts while permission is pending', async () => {
      const mockClasses = [
        { id: 'group-1', name: 'Physics 101', grade_level: 'Grade 10', subject: 'Physics', room: '101', capacity: 30 }
      ];

      const { unmount } = render(
        <AttendanceQRScanner
          classesList={mockClasses}
          selectedGroupId="group-1"
          onSelectGroupId={vi.fn()}
        />
      );

      const startBtn = screen.getByRole('button', { name: /start camera/i });
      fireEvent.click(startBtn);

      // Component unmounts (e.g. user navigates away or logs out)
      unmount();

      // Permission prompt resolves late
      await act(async () => {
        if (getUserMediaResolve) {
          getUserMediaResolve(mockStream);
        }
      });

      // Stream tracks must be stopped immediately
      expect(mockTrack.stop).toHaveBeenCalled();
    });
  });

  describe('2. Real Generated Student Card QR Decoding', () => {
    it('successfully renders a real StudentIdCard badge and decodes its QR code via jsQR', () => {
      const testStudent: StudentCardData = {
        id: '22222222-4444-4444-8888-999999999999',
        full_name: 'Sara Adel',
        student_code: 'ET-3001',
        group_id: 'group-1',
        grade_level: 'Grade 10',
        group_name: 'Physics 101',
        qr_code_hash: 'ET-CARD-VERIFIED-HASH-45678',
        status: 'active',
      };

      // 1. Render actual StudentIdCard to static SVG markup
      const html = ReactDOMServer.renderToStaticMarkup(
        <StudentIdCard student={testStudent} centerName="EduTrack Center" />
      );

      expect(html).toContain('Sara Adel');
      expect(html).toContain('ET-3001');

      // 2. Extract SVG viewBox and black module path generated by QRCodeSVG
      const vbMatch = html.match(/viewBox="0 0 (\d+) (\d+)"/);
      expect(vbMatch).not.toBeNull();
      const gridSize = parseInt(vbMatch![1], 10);
      expect(gridSize).toBeGreaterThan(15);

      // Rasterize the SVG vector modules into a 4-channel Uint8ClampedArray (RGBA) bitmap
      const scale = 8; // 8x8 pixels per QR module for crisp scanning
      const width = gridSize * scale;
      const height = gridSize * scale;
      const pixelBuffer = new Uint8ClampedArray(width * height * 4);
      pixelBuffer.fill(255); // White background

      // Extract the black paths: QRCodeSVG renders path elements with 'M{x},{y} h{w}v{h}H{x}z' or similar
      const pathMatches = html.match(/<path fill="#0f172a" d="([^"]+)"/i) || html.match(/<path fill="#000000" d="([^"]+)"/i);
      expect(pathMatches).not.toBeNull();
      const dAttr = pathMatches![1];

      // Parse commands in path (supports: M x,y or M x y, followed by h/v/H/z)
      const rectRegex = /M\s*(\d+)[,\s]+(\d+)\s*h\s*(\d+)\s*v\s*(\d+)\s*H\s*(\d+)\s*z/gi;
      let match;
      let moduleCount = 0;

      while ((match = rectRegex.exec(dAttr)) !== null) {
        moduleCount++;
        const x = parseInt(match[1], 10);
        const y = parseInt(match[2], 10);
        const w = parseInt(match[3], 10);
        const h = parseInt(match[4], 10);

        for (let py = y * scale; py < (y + h) * scale; py++) {
          for (let px = x * scale; px < (x + w) * scale; px++) {
            const idx = (py * width + px) * 4;
            pixelBuffer[idx] = 0;       // R
            pixelBuffer[idx + 1] = 0;   // G
            pixelBuffer[idx + 2] = 0;   // B
            pixelBuffer[idx + 3] = 255; // A
          }
        }
      }

      expect(moduleCount).toBeGreaterThan(0);

      // 3. Decode the actual rasterized pixel buffer using jsQR (exact same engine used by camera & file upload)
      const decodedResult = jsQR(pixelBuffer, width, height, {
        inversionAttempts: 'dontInvert',
      });

      expect(decodedResult).not.toBeNull();
      expect(decodedResult?.data).toBe('ET-CARD-VERIFIED-HASH-45678');
      expect(decodedResult?.data).toBe(testStudent.qr_code_hash);
    });
  });
});
